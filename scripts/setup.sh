    echo ""
}

# =============================================================================
# CLEANUP FUNCTION
# =============================================================================

cleanup() {
    print_header "CLEANUP: Removing POC resources"
    
    # Load env if available (for variable names), use defaults otherwise
    if [[ -f "$PROJECT_DIR/.env" ]]; then
        set -a
        source "$PROJECT_DIR/.env"
        set +a
    fi
    
    print_step "Stopping containers..."
    cd "$PROJECT_DIR"
    docker compose down 2>/dev/null || true
    docker compose -f docker-compose.airbyte.yaml down -v 2>/dev/null || true
    print_success "Containers stopped"
    
    print_step "Dropping databases..."
    docker exec "$POSTGRES_CONTAINER" psql -U "$POSTGRES_USER" -c "DROP DATABASE IF EXISTS ${GEN_AIRBYTE_DB_NAME};" 2>/dev/null || true
    docker exec "$POSTGRES_CONTAINER" psql -U "$POSTGRES_USER" -c "DROP DATABASE IF EXISTS ${GEN_DBT_DB_NAME};" 2>/dev/null || true
    print_success "Databases dropped"
    
    print_step "Dropping users..."
    docker exec "$POSTGRES_CONTAINER" psql -U "$POSTGRES_USER" -c "DROP USER IF EXISTS ${GEN_DBT_USER};" 2>/dev/null || true
    docker exec "$POSTGRES_CONTAINER" psql -U "$POSTGRES_USER" -c "DROP USER IF EXISTS ${GEN_AIRBYTE_DB_USER};" 2>/dev/null || true
    print_success "Users dropped"
    
    print_step "Removing generated files..."
    rm -f "$PROJECT_DIR/.env.generated" 2>/dev/null || true
    print_success "Generated files removed"
    
    print_header "CLEANUP COMPLETE"
    echo ""
    echo "All POC resources have been removed."
    echo "Your ${POSTGRES_CONTAINER} container and data are intact."
    echo ""
}

