create_databases() {
    print_step "Creating POC databases and users..."
    
    # Check if databases already exist
    if check_database_exists "${GEN_AIRBYTE_DB_NAME}" && check_database_exists "${GEN_DBT_DB_NAME}"; then
        print_info "Databases already exist, skipping creation"
        print_success "Databases verified"
        return 0
    fi
    
    # Create users inline (instead of SQL file for parameterization)
    print_info "Creating users (${GEN_DBT_USER}, ${GEN_AIRBYTE_DB_USER})..."
    
    # Create dbt_user if not exists
    if ! check_user_exists "${GEN_DBT_USER}"; then
        if ! docker exec "$POSTGRES_CONTAINER" psql -U "$POSTGRES_USER" -d postgres -c \
            "CREATE USER ${GEN_DBT_USER} WITH PASSWORD '${GEN_DBT_PASSWORD}';" 2>&1; then
            abort "Failed to create user ${GEN_DBT_USER}"
        fi
        print_info "  Created user: ${GEN_DBT_USER}"
    else
        print_info "  User ${GEN_DBT_USER} already exists"
    fi
    
    # Create airbyte_user if not exists
    if ! check_user_exists "${GEN_AIRBYTE_DB_USER}"; then
        if ! docker exec "$POSTGRES_CONTAINER" psql -U "$POSTGRES_USER" -d postgres -c \
            "CREATE USER ${GEN_AIRBYTE_DB_USER} WITH PASSWORD '${GEN_AIRBYTE_DB_PASSWORD}';" 2>&1; then
            abort "Failed to create user ${GEN_AIRBYTE_DB_USER}"
        fi
        print_info "  Created user: ${GEN_AIRBYTE_DB_USER}"
    else
        print_info "  User ${GEN_AIRBYTE_DB_USER} already exists"
    fi
    
    # Create databases via shell (CREATE DATABASE cannot run inside transaction)
    if ! check_database_exists "${GEN_AIRBYTE_DB_NAME}"; then
        print_info "Creating database: ${GEN_AIRBYTE_DB_NAME}..."
        if ! docker exec "$POSTGRES_CONTAINER" psql -U "$POSTGRES_USER" -d postgres -c \
            "CREATE DATABASE ${GEN_AIRBYTE_DB_NAME} OWNER ${GEN_AIRBYTE_DB_USER};" 2>&1; then
            abort "Failed to create ${GEN_AIRBYTE_DB_NAME} database"
        fi
    fi
    
    if ! check_database_exists "${GEN_DBT_DB_NAME}"; then
        print_info "Creating database: ${GEN_DBT_DB_NAME}..."
        if ! docker exec "$POSTGRES_CONTAINER" psql -U "$POSTGRES_USER" -d postgres -c \
            "CREATE DATABASE ${GEN_DBT_DB_NAME} OWNER ${GEN_DBT_USER};" 2>&1; then
            abort "Failed to create ${GEN_DBT_DB_NAME} database"
        fi
    fi
    
    # Grant cross-database access
    print_info "Granting cross-database access..."
    docker exec "$POSTGRES_CONTAINER" psql -U "$POSTGRES_USER" -d postgres -c \
        "GRANT CONNECT ON DATABASE ${GEN_AIRBYTE_DB_NAME} TO ${GEN_DBT_USER};" 2>&1 || true
    
    # Validate databases were created
    if ! check_database_exists "${GEN_AIRBYTE_DB_NAME}"; then
        abort "Database '${GEN_AIRBYTE_DB_NAME}' was not created"
    fi
    
    if ! check_database_exists "${GEN_DBT_DB_NAME}"; then
        abort "Database '${GEN_DBT_DB_NAME}' was not created"
    fi
    
    # Validate users were created
    if ! check_user_exists "${GEN_AIRBYTE_DB_USER}"; then
        abort "User '${GEN_AIRBYTE_DB_USER}' was not created"
    fi
    
    if ! check_user_exists "${GEN_DBT_USER}"; then
        abort "User '${GEN_DBT_USER}' was not created"
    fi
    
    print_success "Databases and users created successfully"
}

create_schemas() {
    print_step "Creating dbt schemas (staging, marts, gold)..."
    
    # Check if schemas already exist
    if check_schema_exists "${GEN_DBT_DB_NAME}" "staging" && \
       check_schema_exists "${GEN_DBT_DB_NAME}" "marts" && \
       check_schema_exists "${GEN_DBT_DB_NAME}" "gold"; then
        print_info "Schemas already exist, skipping creation"
        print_success "Schemas verified"
        return 0
    fi
    
    # Create schemas inline (parameterized)
    print_info "Creating schemas in ${GEN_DBT_DB_NAME}..."
    docker exec "$POSTGRES_CONTAINER" psql -U "$POSTGRES_USER" -d "${GEN_DBT_DB_NAME}" -c "
        CREATE SCHEMA IF NOT EXISTS staging;
        CREATE SCHEMA IF NOT EXISTS marts;
        CREATE SCHEMA IF NOT EXISTS gold;
        
        GRANT ALL PRIVILEGES ON SCHEMA staging TO ${GEN_DBT_USER};
        GRANT ALL PRIVILEGES ON SCHEMA marts TO ${GEN_DBT_USER};
        GRANT ALL PRIVILEGES ON SCHEMA gold TO ${GEN_DBT_USER};
        GRANT ALL PRIVILEGES ON SCHEMA public TO ${GEN_DBT_USER};
        
        ALTER DEFAULT PRIVILEGES IN SCHEMA staging GRANT ALL ON TABLES TO ${GEN_DBT_USER};
        ALTER DEFAULT PRIVILEGES IN SCHEMA marts GRANT ALL ON TABLES TO ${GEN_DBT_USER};
        ALTER DEFAULT PRIVILEGES IN SCHEMA gold GRANT ALL ON TABLES TO ${GEN_DBT_USER};
    " 2>&1 || abort "Failed to create schemas in ${GEN_DBT_DB_NAME}"
    
    # Validate schemas
    for schema in staging marts gold; do
        if ! check_schema_exists "${GEN_DBT_DB_NAME}" "$schema"; then
            abort "Schema '$schema' was not created in ${GEN_DBT_DB_NAME}"
        fi
    done
    
    print_success "Schemas created successfully"
}

set_permissions() {
    print_step "Setting permissions on ${GEN_AIRBYTE_DB_NAME} database..."
    
    print_info "Granting ${GEN_DBT_USER} read access to ${GEN_AIRBYTE_DB_NAME}..."
    docker exec "$POSTGRES_CONTAINER" psql -U "$POSTGRES_USER" -d "${GEN_AIRBYTE_DB_NAME}" -c "
        GRANT USAGE ON SCHEMA public TO ${GEN_DBT_USER};
        GRANT SELECT ON ALL TABLES IN SCHEMA public TO ${GEN_DBT_USER};
        ALTER DEFAULT PRIVILEGES FOR USER ${GEN_AIRBYTE_DB_USER} IN SCHEMA public
            GRANT SELECT ON TABLES TO ${GEN_DBT_USER};
    " 2>&1 || abort "Failed to set permissions on ${GEN_AIRBYTE_DB_NAME}"
    
    print_success "Permissions configured"
}

start_containers() {
    print_step "Starting Docker containers (dbt + Airflow)..."
    
    cd "$PROJECT_DIR"
    
    # Validate docker-compose.yaml exists
    if [[ ! -f "docker-compose.yaml" ]]; then
        abort "docker-compose.yaml not found in $PROJECT_DIR"
    fi
    
    # Start containers
    print_info "Running docker compose up -d..."
    if ! docker compose up -d 2>&1; then
        abort "Failed to start containers.
       
       Check docker-compose.yaml syntax:
         docker compose config
       
       Check for port conflicts:
         - Airflow uses port 8080
         - Ensure no other service is using this port"
    fi
    
    print_success "Containers started"
}

start_airbyte() {
    print_step "Starting Airbyte containers..."
    
    cd "$PROJECT_DIR"
    
    # Validate docker-compose.airbyte.yaml exists
    if [[ ! -f "docker-compose.airbyte.yaml" ]]; then
        abort "docker-compose.airbyte.yaml not found in $PROJECT_DIR"
    fi
    
    # Start Airbyte containers
    print_info "Running docker compose -f docker-compose.airbyte.yaml up -d..."
