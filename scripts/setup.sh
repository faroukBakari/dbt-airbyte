    if ! docker compose -f docker-compose.airbyte.yaml up -d 2>&1; then
        abort "Failed to start Airbyte containers.
       
       Check docker-compose.airbyte.yaml syntax:
         docker compose -f docker-compose.airbyte.yaml config
       
       Check for port conflicts:
         - Airbyte uses port 8000
         - Ensure no other service is using this port"
    fi
    
    print_success "Airbyte containers started"
}

wait_for_airbyte() {
    print_step "Waiting for Airbyte to be ready..."
    
    print_info "This may take 2-4 minutes on first run..."
    
    # Wait for Airbyte API to respond (with basic auth)
    # 120 attempts * 2 seconds = 4 minutes max
    if check_url_with_retry "$AIRBYTE_URL" "Airbyte" 120 "airbyte:password"; then
        echo ""
        print_success "Airbyte is responding"
        return 0
    fi
    
    echo ""
    print_warning "Airbyte not responding yet"
    print_info "Check status with: docker logs airbyte-server"
    return 1
}

configure_airbyte() {
    print_step "Configuring Airbyte (Source, Destination, Connection)..."
    
    print_info "Running auto-configuration script..."
    print_info "This includes schema discovery which may take 30-60 seconds..."
    
    # Retry configuration up to 5 times with 10s delay
    # (Airbyte backend may need extra time after webapp responds)
    local max_attempts=5
    local attempt=1
    local connection_id
    
    while [[ $attempt -le $max_attempts ]]; do
        # Run configure script: stderr shows logs, stdout returns connection_id only
        if connection_id=$(python3 "$SCRIPT_DIR/configure_airbyte.py"); then
            print_success "Airbyte configured successfully"
            print_info "Connection ID: $connection_id"
            
            # Set the connection ID as an Airflow variable
            print_info "Setting Airflow variable 'airbyte_connection_id'..."
            if docker exec airflow airflow variables set airbyte_connection_id "$connection_id" &>/dev/null; then
                print_success "Airflow variable set successfully"
            else
                print_warning "Could not set Airflow variable automatically"
                print_info "Set it manually in Airflow UI: Admin → Variables"
                print_info "  Key: airbyte_connection_id"
                print_info "  Value: $connection_id"
            fi
            
            export AIRBYTE_CONNECTION_ID="$connection_id"
            return 0
        fi
        
        print_info "Airbyte backend not ready yet, retrying in 10s... ($attempt/$max_attempts)"
        sleep 10
        ((attempt++))
    done
    
    print_warning "Airbyte auto-configuration failed after $max_attempts attempts"
    print_info "You can configure Airbyte manually via the UI: $AIRBYTE_URL"
    return 1
}

wait_for_airflow() {
    print_step "Waiting for Airflow to be ready..."
    
    local max_attempts=60
    local attempt=1
    
    print_info "This may take 60-90 seconds on first run..."
    
    # First wait for container to be running
    while [[ $attempt -le 15 ]]; do
        if docker exec airflow airflow db check &> /dev/null; then
            break
        fi
        printf "  Initializing Airflow database... (%d/15)\r" "$attempt"
        sleep 2
        ((attempt++))
    done
    echo ""
    
    # Then wait for web server to respond
    print_info "Waiting for Airflow web server..."
    if check_url_with_retry "$AIRFLOW_HEALTH_URL" "Airflow" 45; then
        echo ""
        print_success "Airflow web server is responding"
        return 0
    fi
    
    echo ""
    print_warning "Airflow web server not responding yet"
    print_info "This might be normal on first run. The service may still be starting."
    print_info "Check status with: docker logs airflow"
    return 1
}

