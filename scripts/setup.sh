check_all_services() {
    local with_airbyte="${1:-false}"
    
    print_step "Verifying all services are accessible..."
    
    local all_ok=true
    
    # Check Airbyte (if enabled)
    if [[ "$with_airbyte" == "true" ]]; then
        print_info "Checking Airbyte UI..."
        if check_url_responding "$AIRBYTE_URL" 5 "airbyte:password"; then
            AIRBYTE_STATUS="${GREEN}● ONLINE${NC}"
        else
            AIRBYTE_STATUS="${YELLOW}○ STARTING${NC}"
        fi
    else
        AIRBYTE_STATUS="${YELLOW}○ DISABLED${NC}"
    fi
    
    # Check Airflow UI
    print_info "Checking Airflow UI..."
    if check_url_responding "$AIRFLOW_URL" 5; then
        AIRFLOW_STATUS="${GREEN}● ONLINE${NC}"
    else
        AIRFLOW_STATUS="${RED}○ OFFLINE${NC}"
        all_ok=false
    fi
    
    # Check PostgreSQL
    print_info "Checking PostgreSQL..."
    if docker exec "$POSTGRES_CONTAINER" pg_isready -U "$POSTGRES_USER" &> /dev/null; then
        POSTGRES_STATUS="${GREEN}● ONLINE${NC}"
    else
        POSTGRES_STATUS="${RED}○ OFFLINE${NC}"
        all_ok=false
    fi
    
    # Check dbt container
    print_info "Checking dbt container..."
    if docker exec dbt-runner dbt --version &> /dev/null; then
        DBT_STATUS="${GREEN}● READY${NC}"
    else
        DBT_STATUS="${RED}○ NOT READY${NC}"
        all_ok=false
    fi
    
    echo ""
    
    if $all_ok; then
        print_success "All services are online and healthy"
    else
        print_warning "Some services are not fully ready yet"
    fi
    
    return 0
}

print_service_urls() {
    local with_airbyte="${1:-false}"
    
    echo ""
    echo "┌─────────────────────────────────────────────────────────────────────┐"
    echo "│                        SERVICE STATUS                              │"
    echo "├─────────────────────────────────────────────────────────────────────┤"
    printf "│  %-11s %-17s %-26s %-11s│\n" "Service" "Status" "URL" "Credentials"
    echo "├─────────────────────────────────────────────────────────────────────┤"
    # Note: Status strings contain ANSI color codes (11 hidden chars), so we use %-28b for 17 visible chars
    printf "│  %-11s %-28b %-26s %-11s│\n" "Airbyte" "$AIRBYTE_STATUS" "$AIRBYTE_URL" "${GEN_AIRBYTE_WEB_USER}/${GEN_AIRBYTE_WEB_PASSWORD}"
